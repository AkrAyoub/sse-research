"""SSE-POS-01: create a self-owned Ethereum PoS devnet plan and genesis funding.

NO real ETH. NO secret, wallet or consensus authority belongs in GitHub.
The experimental chain is 31339, deliberately isolated from Anvil31337
and abandoned permissioned QBFT31338.

This is a *network bootstrap* tool. It produces a protected Kurtosis
ethereum-package args file with a fresh, unshared research-only BIP39
genesis-validator mnemonic, initial validator count and EOA balances
minted in the chain's own genesis. Future validators use Ethereum's
deposit/activation protocol rather than SSE admin grants.

IMPORTANT: a genesis with keys centrally generated by one lab operator
is only a provisional bootstrap. The research network does NOT have
real economic Sybil resistance, Internet P2P or permissionless peer
discovery until those separate acceptance tests are completed.
"""
