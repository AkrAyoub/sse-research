"""Produce the exact professor-required milestone archive from a completed PDF.

Usage: python scripts/package_milestone3.py --pdf path/to/FINAL.pdf --out Milestone_III.zip
No source mutation, compiler invocation or cloud access.
"""
import argparse
from pathlib import Path
import zipfile
import re
from pypdf import PdfReader


def package(root: Path, pdf: Path, out: Path):
    if not pdf.is_file() or pdf.suffix.lower() != '.pdf' or pdf.read_bytes()[:5] != b'%PDF-':
        raise ValueError('provide an existing valid PDF; final paper cannot be generated by this script')
    reader = PdfReader(str(pdf))
    if len(reader.pages) < 1 or len(reader.pages) > 6:
        raise ValueError(f'article must be 1–6 pages; found {len(reader.pages)}')
    content = "\n".join(page.extract_text() or "" for page in reader.pages).lower()
    disclaimer = content.rfind('ai usage disclaimer')
    references = content.rfind('references')
    if disclaimer < 0 or references < 0 or disclaimer > references:
        raise ValueError('article must contain an AI Usage Disclaimer BEFORE References')
    contracts = sorted((root/'contracts').glob('*.sol'))
    if len(contracts) != 5:
        raise ValueError('expected the five current first-party contracts in contracts/')
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out,'w',compression=zipfile.ZIP_DEFLATED) as z:
        z.write(pdf, 'Article.pdf')
        for src in contracts:
            z.write(src, 'contracts/'+src.name)
    return out


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--pdf',type=Path,required=True)
    p.add_argument('--out',type=Path,default=Path('Milestone_III.zip'))
    args=p.parse_args()
    try: print(package(Path(__file__).resolve().parents[1],args.pdf,args.out))
    except (ValueError,OSError) as exc: p.error(str(exc))

if __name__=='__main__': main()
